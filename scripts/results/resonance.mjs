#!/usr/bin/env node
// Scores the paid-content export with Resonance r1 and writes the inspectable result.
//
//   node scripts/results/resonance.mjs [--csv <path>] [--out <path>] [--sensitivity] [--trace <creative id>]
//
//   --csv          defaults to docs/reports/paid-content-through-set-4.csv
//   --out          defaults to src/lib/resonance/scores.ts (generated, committed)
//   --sensitivity  also prints how the scores move under one changed input and changed assumptions,
//                  and how r1 orders creatives against single measures (docs/reports/resonance-r1.md)
//   --trace <id>   prints one creative's path from raw rows to its score
//
// The formula itself is src/lib/resonance/formula.ts (pure, versioned); this script only reads the CSV,
// calls scoreDataset, and writes. It transpiles the formula in memory, so there is one source of truth.

import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import { createRequire } from "node:module"

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..")
const require = createRequire(path.join(ROOT, "package.json"))
const ts = require("typescript")
const argv = process.argv.slice(2)
const flag = (n) => (argv.includes(`--${n}`) ? argv[argv.indexOf(`--${n}`) + 1] : undefined)
const csvPath = flag("csv") ?? path.join(ROOT, "docs/reports/paid-content-through-set-4.csv")
const outPath = flag("out") ?? path.join(ROOT, "src/lib/resonance/scores.ts")

// -- the formula --------------------------------------------------------------------------------
const src = fs.readFileSync(path.join(ROOT, "src/lib/resonance/formula.ts"), "utf8")
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "resonance-")), "formula.mjs")
fs.writeFileSync(tmp, js)
const { scoreDataset, FORMULA_VERSION, COMPONENTS } = await import(tmp)

// -- the CSV ------------------------------------------------------------------------------------
function parseCsv(text) {
  const lines = text.replace(/\r/g, "").split("\n").filter((l) => l.length)
  const split = (l) => {
    const out = []
    let cur = ""
    let q = false
    for (let i = 0; i < l.length; i++) {
      const ch = l[i]
      if (q) {
        if (ch === '"' && l[i + 1] === '"') (cur += '"'), i++
        else if (ch === '"') q = false
        else cur += ch
      } else if (ch === '"') q = true
      else if (ch === ",") out.push(cur), (cur = "")
      else cur += ch
    }
    out.push(cur)
    return out
  }
  const head = split(lines[0])
  return lines.slice(1).map((l) => Object.fromEntries(split(l).map((v, i) => [head[i], v])))
}
const num = (v) => (v === undefined || v.trim() === "" ? null : Number(v))
const raw = parseCsv(fs.readFileSync(csvPath, "utf8"))
const rows = raw.map((r) => ({
  recordId: r.record_id,
  reportDate: r.report_date,
  setId: r.creative_set_id,
  creativeId: r.creative_id,
  creativeName: r.creative_name,
  durationSeconds: num(r.duration_seconds),
  audience: r.audience_group,
  age: r.age_group,
  spendUsd: num(r.spend_usd),
  impressions: num(r.impressions) ?? 0,
  clicks: num(r.clicks) ?? 0,
  starts: num(r.video_starts) ?? 0,
  completions: num(r.video_completions_reported) ?? 0,
  views15s: num(r.views_15s_thruplays_reported) ?? 0,
}))
const blankDerived = raw.filter((r) => Object.entries(r).some(([k, v]) => /_(pct|usd)$/.test(k) && v.trim() === "")).length

const result = scoreDataset(rows)
const scored = result.scores.filter((s) => s.score !== null)
console.log(`${FORMULA_VERSION}: ${rows.length} rows, ${result.reference.creatives} creatives, ${result.reference.strata.length} strata; ${blankDerived} rows with a blank derived cell (not read)`)
console.log(`duration fit: ln(completion) = ${result.durationFit.intercept} + ${result.durationFit.slope} × ln(seconds), ${result.durationFit.rows} rows, r² ${result.durationFit.rSquared}`)
for (const s of [...result.scores].sort((a, b) => (b.score ?? -1) - (a.score ?? -1)))
  console.log(`  ${String(s.score ?? "—").padStart(5)}  ${s.status.padEnd(10)} ${s.creativeId} ${s.creativeName}  [${s.components.map((c) => `${c.id} ${c.value ?? "—"}`).join(", ")}]`)

const header = `// Generated by scripts/results/resonance.mjs from ${path.relative(ROOT, csvPath)} with formula ${FORMULA_VERSION} — do not edit by hand.
// Per creative: the inputs used (one row per delivery cell, counts as reported), each component's
// within-cell percentiles, value, weight and contribution, the score, the version, and the flags.
import type { ScoredDataset } from "./formula"

export const RESONANCE_R1: ScoredDataset = `
fs.writeFileSync(outPath, header + JSON.stringify(result, null, 2) + "\n")
console.log(`wrote ${path.relative(ROOT, outPath)} (${scored.length} scored or partial, ${result.scores.length - scored.length} unscorable)`)

// -- one creative, traced -----------------------------------------------------------------------
const traceId = flag("trace")
if (traceId) {
  const s = result.scores.find((x) => x.creativeId === traceId)
  console.log(`\n== trace ${traceId}: ${s.creativeName} (${s.durationSeconds} s, ${s.setId})`)
  for (const i of s.inputs)
    console.log(`  ${i.recordId} ${i.stratum.padEnd(24)} impr ${i.impressions} starts ${i.starts} 15s ${i.views15s} compl ${i.completions} clicks ${i.clicks} → stop ${i.rates.stop} hold15 ${i.rates.hold15} finish ${i.rates.finish} act ${i.rates.act}`)
  for (const c of s.components) {
    console.log(`  ${c.name}: ${c.perStratum.map((p) => `${p.stratum} ${p.percentile ?? "—"} (of ${p.peers})`).join("; ")}`)
    console.log(`    value ${c.value} × weight ${c.effectiveWeight} = ${c.contribution}`)
  }
  console.log(`  score ${s.score}; flags: ${s.flags.join(" | ") || "none"}`)
}

// -- sensitivity --------------------------------------------------------------------------------
if (argv.includes("--sensitivity")) {
  const byId = (d) => Object.fromEntries(d.scores.map((s) => [s.creativeId, s.score]))
  const base = byId(result)
  const rank = (m) => {
    const ids = Object.keys(m).filter((k) => m[k] !== null).sort((a, b) => m[b] - m[a])
    return Object.fromEntries(ids.map((k, i) => [k, i + 1]))
  }
  const spearman = (a, b) => {
    const ra = rank(a), rb = rank(b)
    const ids = Object.keys(ra).filter((k) => k in rb)
    const n = ids.length
    const d2 = ids.reduce((t, k) => t + (ra[k] - rb[k]) ** 2, 0)
    return 1 - (6 * d2) / (n * (n * n - 1))
  }
  const compare = (label, d) => {
    const alt = byId(d)
    const deltas = Object.keys(base).filter((k) => base[k] !== null && alt[k] !== null).map((k) => [k, alt[k] - base[k]])
    const max = deltas.reduce((m, x) => (Math.abs(x[1]) > Math.abs(m[1]) ? x : m), ["", 0])
    const top = (m) => Object.entries(rank(m)).filter(([, r]) => r <= 5).map(([k]) => k).sort().join(",")
    console.log(`  ${label.padEnd(58)} Spearman ${spearman(base, alt).toFixed(3)}; largest move ${max[0]} ${max[1] > 0 ? "+" : ""}${max[1].toFixed(1)}; top-5 ${top(alt) === top(base) ? "unchanged" : `now ${top(alt)} (was ${top(base)})`}`)
  }
  console.log("\n== sensitivity")
  // One input changed: a single row's 15-second views up 20%.
  const r = rows.find((x) => x.recordId === "R001")
  const bumped = rows.map((x) => (x.recordId === "R001" ? { ...x, views15s: Math.round(x.views15s * 1.2) } : x))
  const one = byId(scoreDataset(bumped))
  console.log(`  R001 (C001, ${r.audience} · ${r.age}) 15-second views ${r.views15s} → ${Math.round(r.views15s * 1.2)}: C001 ${base.C001} → ${one.C001}; others moved ${Object.keys(base).filter((k) => k !== "C001" && one[k] !== base[k]).length}`)
  compare("equal weights (25/25/25/25)", scoreDataset(rows, { weights: { stop: 1, hold15: 1, finish: 1, act: 1 } }))
  compare("without Act (clicks)", scoreDataset(rows, { weights: { act: 0 } }))
  compare("compared within audience × age × set", scoreDataset(rows, { stratify: "audience-age-set" }))
  compare("finish not adjusted for length", scoreDataset(rows, { durationAdjust: false }))
  // Against single measures.
  console.log("\n== against single measures (Spearman with r1)")
  const agg = (f) => Object.fromEntries(result.scores.map((s) => [s.creativeId, f(rows.filter((x) => x.creativeId === s.creativeId))]))
  const sum = (rs, k) => rs.reduce((t, x) => t + x[k], 0)
  const singles = {
    "completion rate (completions ÷ starts)": agg((rs) => sum(rs, "completions") / sum(rs, "starts")),
    "15-second views per impression": agg((rs) => sum(rs, "views15s") / sum(rs, "impressions")),
    "click-through rate": agg((rs) => sum(rs, "clicks") / sum(rs, "impressions")),
    "cost per 15-second view (lower first)": agg((rs) => -rs.reduce((t, x) => t + (x.spendUsd ?? 0), 0) / sum(rs, "views15s")),
  }
  for (const [label, m] of Object.entries(singles)) {
    const rk = rank(m), rr = rank(base)
    const far = Object.keys(rr).map((k) => [k, rk[k] - rr[k]]).sort((a, b) => Math.abs(b[1]) - Math.abs(a[1])).slice(0, 2)
    console.log(`  ${label.padEnd(44)} ${spearman(base, m).toFixed(3)}; furthest apart: ${far.map(([k, d]) => `${k} (r1 #${rr[k]}, this #${rk[k]})`).join(", ")}`)
  }
  void COMPONENTS
}
